package com.example.domain.model

/**
 * Элемент локального справочника лекарств. Прототип интеграции с Реестром ЛС РК:
 * данные зашиты в приложение и пополняются вручную при пересборке. Сравнение
 * `registeredInKz` помогает пользователю отличить препараты, доступные в аптеках РК,
 * от привезённых из-за рубежа аналогов.
 */
data class MedicationCatalogItem(
    /** Международное непатентованное наименование (МНН). */
    val inn: String,
    /** Распространённое торговое название на рынке РК. */
    val tradeName: String,
    val form: MedicationForm,
    /** Зарегистрирован ли препарат в Государственном реестре ЛС РК. */
    val registeredInKz: Boolean,
    /** Терапевтическая группа для группировки в UI (например, «Сердечно-сосудистые»). */
    val group: String,
    /** Дополнительная заметка — например, «по рецепту», «безрецептурный». */
    val note: String? = null,
)
